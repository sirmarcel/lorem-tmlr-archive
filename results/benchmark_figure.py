"""Overview figure for the paper: Ewald vs PME scaling across three
crystal types.

Uses the **light** regime of the matched-accuracy re-run, collected
into `../evals/benchmark-revision/`: Ewald `lr_wavelength=cutoff/4`, PME
`mesh_spacing=cutoff/8`, both at F_rel ≈ 1.3e-2 on rattled NaCl-64 (the
accuracy the original benchmark's PME setting was actually delivering).

The N range is capped at the original paper's coverage (~33k atoms)
so the figure shape matches the originally-submitted version. The
data archive carries the full coverage (NaCl PME to 85k, etc.); see
`benchmark_full_figure.py` for the un-capped version.

The pre-revision (mismatched) figure is regenerated by
`benchmark_figure_broken.py`.
"""

from tbx import *
from benchmark import CRYSTALS, CRYSTAL_LABELS, get_table_data

crystal_colors = {"nacl": black, "cscl": teal, "cu2o": red}
crystal_markers = {"nacl": bigdot, "cscl": square, "cu2o": diamond}
crystal_ms = {"nacl": 4, "cscl": 3.5, "cu2o": 3.5}

# Cap N to the originally-submitted paper's coverage; full data lives in
# benchmark_full_figure.py.
N_MAX_PAPER = 33000

fig, ax = fig_and_ax(figsize=(textwidth, 3.5))

for crystal in CRYSTALS:
    sizes, t_ewald, t_pme, t_nolr, lr_ewald, lr_pme = get_table_data(crystal)
    keep = sizes <= N_MAX_PAPER
    sizes = sizes[keep]
    t_ewald = t_ewald[keep]
    t_pme = t_pme[keep]

    label = CRYSTAL_LABELS[crystal]
    c = crystal_colors[crystal]
    m = crystal_markers[crystal]
    ms = crystal_ms[crystal]

    ewald_mask = ~np.isnan(t_ewald)
    ax.plot(
        sizes[ewald_mask],
        1e3 * t_ewald[ewald_mask],
        color=c, marker=m, markersize=ms,
        linestyle=dashed, linewidth=1.0,
        label=f"{label} (Ewald)",
    )

    ax.plot(
        sizes,
        1e3 * t_pme,
        color=c, marker=m, markersize=ms,
        linestyle=solid, linewidth=1.5,
        label=f"{label} (PME)",
    )

# Reference lines anchored to NaCl light data at N=1000:
#   Ewald light NaCl @ N=1000 ≈ 4.5 ms; PME NaCl @ N=1000 ≈ 3 ms.
n_ref = np.array([200, 40000])
t_n2 = 4.5 * (n_ref / 1000) ** 2
t_n1 = 3 * (n_ref / 1000) ** 1
ax.plot(
    n_ref, t_n2, color=grey, linestyle=dotted, linewidth=0.8,
    label=r"$\propto N^2$",
)
ax.plot(
    n_ref, t_n1, color=grey, linestyle=finedash, linewidth=0.8,
    label=r"$\propto N$",
)

ax.set_xscale("log")
ax.set_yscale("log")
ax.set_xlabel(r"Number of atoms $N$")
ax.set_ylabel("Inference time (ms)")
ax.set_ylim(0.4, 2000)
ax.legend(fontsize=7, ncol=2)

savefig(fig, "figures/benchmark_scaling")
